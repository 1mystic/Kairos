"""Bank statistics.  python -m pipeline.stats [--src DIR ...] [--md content/sources/bank_stats.md]

Prints (and optionally writes as markdown) the per-chapter question table: counts by source, type and
difficulty, and how many questions are actually served from the JEE_MAIN / NEET_UG / IAT shards.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

from .paths import DEFAULT_SRCS, SOURCES_DIR
from .schema import Question
from .tag import manual_tags
from .taxonomy import default_taxonomy
from .validate import collect_files

TYPES = ("SCQ", "MSQ", "NVQ", "INT")


def load_questions(srcs: list[Path]) -> list[Question]:
    tax = default_taxonomy()
    out: list[Question] = []
    for f in collect_files(list(srcs)):
        data = json.loads(f.read_text(encoding="utf-8"))
        items = data.get("questions") if isinstance(data, dict) else data
        out += [Question.model_validate(r, context={"taxonomy": tax}) for r in items]
    return out


def build_tables(qs: list[Question]) -> tuple[list[list[str]], list[str]]:
    tax = default_taxonomy()
    by_ch: dict[str, list[Question]] = {}
    for q in qs:
        by_ch.setdefault(q.tax.chapter, []).append(q)
    manual = manual_tags()
    hdr = ["chapter", "name", "total", "authored", "dataset", "SCQ", "MSQ", "NVQ", "INT", "E", "M", "H",
           "JEE_MAIN", "NEET_UG", "IAT", "manual-tag"]
    rows = []
    for s in tax.subjects:
        for c in s.chapters:
            lst = by_ch.get(c.id, [])
            ty = Counter(q.type for q in lst)
            dl = Counter(q.difficulty.label for q in lst if q.difficulty)
            ex = Counter(e for q in lst if q.status == "verified" for e in q.exams())
            rows.append([c.id, c.name, len(lst), sum(q.source.kind == "authored" for q in lst),
                         sum(q.source.kind == "dataset" for q in lst),
                         *(ty[t] for t in TYPES), dl["E"], dl["M"], dl["H"],
                         ex["JEE_MAIN"], ex["NEET_UG"], ex["IAT"], sum(q.id in manual for q in lst)])
    totals = ["TOTAL", "", *[sum(int(r[i]) for r in rows) for i in range(2, len(hdr))]]
    rows.append(totals)
    unrouted = sum(1 for q in qs if q.status == "verified" and not q.exams())
    extra = [
        f"questions: {len(qs)} (verified {sum(q.status == 'verified' for q in qs)})",
        "by year (JEE_ADV appearances): " + ", ".join(
            f"{y}: {n}" for y, n in sorted(Counter(a.year for q in qs for a in q.appearances if a.exam == 'JEE_ADV').items())),
        "by source: " + ", ".join(f"{k}: {n}" for k, n in sorted(Counter(q.source.kind for q in qs).items())),
        f"not served from any shard (Advanced-only chapters, JEE_MAIN flag false): {unrouted}",
    ]
    return [hdr] + rows, extra


def to_markdown(table: list[list[str]], extra: list[str]) -> str:
    hdr, *rows = table
    lines = ["# Question bank statistics", "",
             "Generated by `python -m pipeline.stats --md content/sources/bank_stats.md`. Do not edit by hand.", ""]
    lines += [f"- {e}" for e in extra] + [""]
    lines.append("| " + " | ".join(hdr) + " |")
    lines.append("|" + "|".join("---" if i < 2 else "---:" for i in range(len(hdr))) + "|")
    for r in rows:
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(lines) + "\n"


def to_text(table: list[list[str]], extra: list[str]) -> str:
    widths = [max(len(str(r[i])) for r in table) for i in range(len(table[0]))]
    widths[1] = min(widths[1], 34)
    out = list(extra) + [""]
    for r in table:
        out.append("  ".join(str(x)[: widths[i]].ljust(widths[i]) if i < 2 else str(x).rjust(max(widths[i], 3))
                             for i, x in enumerate(r)))
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="pipeline.stats", description=__doc__)
    ap.add_argument("--src", type=Path, action="append", default=None)
    ap.add_argument("--md", type=Path, nargs="?", const=SOURCES_DIR / "bank_stats.md", default=None,
                    help="also write the markdown table (default path content/sources/bank_stats.md)")
    a = ap.parse_args(argv)
    qs = load_questions(a.src or list(DEFAULT_SRCS))
    table, extra = build_tables(qs)
    print(to_text(table, extra))
    if a.md:
        a.md.parent.mkdir(parents=True, exist_ok=True)
        a.md.write_text(to_markdown(table, extra), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
